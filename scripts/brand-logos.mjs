// Writes src/app/utils/brandLogos.ts from public/assets/images/TireBrand (055).
//
// Run after adding or removing a `{brandId}-logo.webp`:  node scripts/brand-logos.mjs
// The list lets the site show a brand's name as text — without requesting a
// file that does not exist (a 404 per card) — for any brand with no logo.
// `brandLogos.test.ts` fails if the folder and the list ever disagree.

import { execFileSync } from 'node:child_process';
import { readdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

export const LOGO_DIR = new URL('../public/assets/images/TireBrand/', import.meta.url);

/** Brand ids that have a `{id}-logo.webp`, ascending. Pure over a file list. */
export function logoIds(files) {
  return files
    .map(f => /^(\d+)-logo\.webp$/.exec(f)?.[1])
    .filter(Boolean)
    .map(Number)
    .sort((a, b) => a - b);
}

export function render(ids) {
  return `// Generated by scripts/brand-logos.mjs from public/assets/images/TireBrand.
// Do not edit by hand: add or remove the file, then run \`node scripts/brand-logos.mjs\`.

/** Brand ids with a logo file (\`/assets/images/TireBrand/{id}-logo.webp\`). */
export const BRAND_LOGO_IDS: ReadonlySet<number> = new Set([
${ids.map(id => `  ${id},`).join('\n')}
]);

export const hasBrandLogo = (brandId: number | null | undefined): brandId is number =>
  typeof brandId === 'number' && BRAND_LOGO_IDS.has(brandId);

export const brandLogoSrc = (brandId: number) => \`/assets/images/TireBrand/\${brandId}-logo.webp\`;
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const ids = logoIds(readdirSync(LOGO_DIR));
  const out = fileURLToPath(new URL('../src/app/utils/brandLogos.ts', import.meta.url));
  writeFileSync(out, render(ids));
  execFileSync('npx', ['prettier', '--write', out], { stdio: 'ignore' });
  console.log(`brandLogos.ts: ${ids.length} brands with a logo`);
}
